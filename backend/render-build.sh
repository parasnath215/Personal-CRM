#!/usr/bin/env bash
set -o errexit

echo "Running custom render-build.sh..."

# Install system dependencies for headless Chromium if running with package manager access
if command -v apt-get &> /dev/null; then
  echo "Checking/installing system libraries for Headless Chrome..."
  apt-get update && apt-get install -y \
    ca-certificates \
    fonts-liberation \
    libasound2 \
    libatk-bridge2.0-0 \
    libatk1.0-0 \
    libc6 \
    libcairo2 \
    libcups2 \
    libdbus-1-3 \
    libexpat1 \
    libfontconfig1 \
    libgbm1 \
    libgcc1 \
    libglib2.0-0 \
    libgtk-3-0 \
    libnspr4 \
    libpango-1.0-0 \
    libpangocairo-1.0-0 \
    libstdc++6 \
    libx11-6 \
    libx11-xcb1 \
    libxcb1 \
    libxcomposite1 \
    libxcursor1 \
    libxdamage1 \
    libxext6 \
    libxfixes3 \
    libxi6 \
    libxrandr2 \
    libxrender1 \
    libxss1 \
    libxtst6 \
    xdg-utils || true
fi

npm install
npx prisma generate
npx prisma db push
npx puppeteer browsers install chrome

echo "Build script completed successfully."
